package com.briefai.conversation.dto;

import com.briefai.conversation.entity.ChatMessageRole;

import java.time.LocalDateTime;

public class ChatMessageResponse {
    private Long id;
    private ChatMessageRole role;
    private String content;
    private LocalDateTime createdAt;

    public ChatMessageResponse(Long id, ChatMessageRole role, String content, LocalDateTime createdAt) {
        this.id = id;
        this.role = role;
        this.content = content;
        this.createdAt = createdAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public ChatMessageRole getRole() {
        return role;
    }

    public void setRole(ChatMessageRole role) {
        this.role = role;
    }

    public String getContent() {
        return content;
    }

    public void setContent(String content) {
        this.content = content;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
}
